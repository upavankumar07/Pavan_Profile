function animateBars(panel) {
  if (!panel) return;
  panel.querySelectorAll('.sk-card').forEach(function (card) {
    var bar = card.querySelector('.sk-bar');
    if (!bar) return;
    bar.style.width = '0';
    setTimeout(function () { bar.style.width = (card.getAttribute('data-pct') || '0') + '%'; }, 80);
  });
}

