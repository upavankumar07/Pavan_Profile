var currentLang = 'en';

/* Display names shown in the trigger button */
var LANG_DISPLAY = {
  en: 'English', de: 'Allemand', fr: 'Français',
  ja: 'Japonais', ko: 'Coréen',  zh: 'Chinois'
};

function applyLanguage(lang) {
  var t = TRANSLATIONS[lang];
  if (!t) { console.warn('No translation for:', lang); return; }
  currentLang = lang;

  /* 1. Text content */
  var els = document.querySelectorAll('[data-i18n]');
  for (var i = 0; i < els.length; i++) {
    var key = els[i].getAttribute('data-i18n');
    if (t[key] !== undefined) els[i].innerHTML = t[key];
  }

  /* 2. Input placeholders */
  var phs = document.querySelectorAll('[data-i18n-ph]');
  for (var j = 0; j < phs.length; j++) {
    var pk = phs[j].getAttribute('data-i18n-ph');
    if (t[pk] !== undefined) phs[j].placeholder = t[pk];
  }

  /* 3. Dropdown: active row + checkmark + trigger label */
  var allLangs = ['en','de','fr','ja','ko','zh'];
  for (var k = 0; k < allLangs.length; k++) {
    var l   = allLangs[k];
    var btn = document.getElementById('lb-' + l);
    var chk = document.getElementById('chk-' + l);
    if (btn) btn.classList.toggle('active', l === lang);
    if (chk) chk.textContent = (l === lang) ? '✓' : '';
  }

  /* 4. Update trigger label */
  var lbl = document.getElementById('langLabel');
  if (lbl) lbl.textContent = LANG_DISPLAY[lang] || lang.toUpperCase();

  /* 5. Close dropdown */
  var sw = document.getElementById('langSwitcher');
  if (sw) sw.classList.remove('open');

  /* 6. html lang attr */
  document.documentElement.lang = lang;

  /* 7. Persist */
  try { localStorage.setItem('pk-lang', lang); } catch(e) {}
}

